function svgFor(elements, background = paper) {
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">',
    `<rect width="512" height="512" fill="${background}"/>`,
    '<g opacity="0.98">',
    ...elements.map((element) => `  ${element}`),
    '</g>',
    '</svg>',
  ].join('\n') + '\n';
}

const slugs = new Set();
for (const item of outputArt) {
  if (slugs.has(item.slug)) throw new Error(`Duplicate artwork: ${item.slug}`);
  slugs.add(item.slug);
  if (item.steps.length < 5 || item.steps.length > 8) throw new Error(`${item.slug} must have between five and eight steps`);
  const folder = path.join(root, item.slug);
  fs.mkdirSync(folder, { recursive: true });
  const cumulative = [];
  const background = animalSlugs.has(item.slug) ? '#F3DCCE' : paper;
  for (let index = 0; index < item.steps.length; index += 1) {
    cumulative.push(...item.steps[index]);
    fs.writeFileSync(path.join(folder, `step_${String(index + 1).padStart(2, '0')}.svg`), svgFor(cumulative, background));
  }
  fs.writeFileSync(path.join(folder, 'final_preview.svg'), svgFor(cumulative, background));
}

